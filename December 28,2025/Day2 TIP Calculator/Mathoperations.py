#mathematical operations in Python
print("Addition:", 5 + 3)          # Addition and it will return 8
print("Subtraction:", 10 - 4)      # Subtraction  and it will return 6  
print("Multiplication:", 7 * 6)    # Multiplication and it will return 42
print("Division:", 18 / 5)         # Division and it will return 3.6
print("Floor Division:", 20 // 3)   # Floor Division and it will return 6
print("Modulus:", 10 % 3)          # Modulus and it will return 1
print("Exponentiation:", 2 ** 4)   # Exponentiation and it will return 16
print("Square Root of 16:", 16 ** 0.5)  # Square Root and it will return 4.0
#basic divison by / returns float value
print("Integer Division of 7 / 2:", 7 / 2)  # Returns float value
#floor division by // returns integer value
print("Floor Division of 7 // 2:", 7 // 2)  # Returns integer value

#PEMDAS/BODMAS rule
# Parentheses, Exponents, Multiplication and Division (from left to right), Addition and Subtraction (from left to right)
result = (3 + 5) * 2 ** 3 / 4 - 6
print("Result of (3 + 5) * 2 ** 3 / 4 - 6:", result)  # It will return 10.0