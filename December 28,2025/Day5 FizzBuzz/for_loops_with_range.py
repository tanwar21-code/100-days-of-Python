#adding number from 1 to 100 using for loop with range
sum = 0
for i in range(1,101):
    sum +=i
print(sum)

#prnting numbers
for number in range(1,11,2):
    print(number)  #prints odd numbers from 1 to 10

for number in range(0,11,2):
    print(number)  #prints even numbers from 0 to 10

for number in range(5):
    print(number)  #prints numbers from 0 to 4

for number in range(2,21,5):
    print(number)  #prints numbers from 2 to 20 with step of 5
    